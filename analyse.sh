#!/usr/bin/env bash
# COMP3010 CW1 - reproducible evidence extraction
# Usage: ./analyse.sh <COMP3010CW1.pcap> <CW1Snort.txt> <CW1Suricata.txt> <output_dir>
# Requires: tshark, python3, sha256sum. All times are UTC.
set -euo pipefail
PCAP=$1; SNORT=$2; SURI=$3; OUT=$4
export TZ=UTC
mkdir -p "$OUT"
ts() { awk -F'\t' 'BEGIN{OFS=","} {gsub(/"/,"",$1); $1=strftime("%Y-%m-%d %H:%M:%S",$1); print}'; }

# 1. IDS alert summaries
{
  echo "Total Snort alerts: $(grep -c '^\[\*\*\]' "$SNORT")"
  echo "Alerts naming 192.168.1.96: $(grep -A3 '^\[\*\*\]' "$SNORT" | grep -c '192\.168\.1\.96' )"
  echo; echo "Count  Signature"
  grep -oE '^\[\*\*\] \[[0-9:]+\] .* \[\*\*\]' "$SNORT" | sort | uniq -c | sort -rn
} > "$OUT/01_snort_alert_summary.txt"
{
  echo "Total Suricata alerts: $(grep -c '^Count:' "$SURI")"
  echo "Note: Suricata timestamps are offset by about +10h36m (alerts generated by replaying the pcap)."
  echo; echo "Count  Signature"
  awk '/^Count:/{getline; print}' "$SURI" | sort | uniq -c | sort -rn
} > "$OUT/02_suricata_alert_summary.txt"

# 2. Host identification (DHCP)
{ echo "time_utc,src_mac,src_ip,dhcp_msg_type,hostname"
  tshark -r "$PCAP" -Y 'dhcp && ip.src==192.168.1.96' -T fields -e frame.time_epoch -e eth.src -e ip.src -e dhcp.option.dhcp -e dhcp.option.hostname | ts
} > "$OUT/03_dhcp_host_identity.csv"

# 3. All HTTP requests from the host
{ echo "time_utc,frame,dst_ip,method,host,uri,user_agent"
  tshark -r "$PCAP" -Y http.request -T fields -E quote=d -e frame.time_epoch -e frame.number -e ip.dst -e http.request.method -e http.host -e http.request.uri -e http.user_agent | ts
} > "$OUT/04_http_requests.csv"
{ echo "count,user_agent"
  tshark -r "$PCAP" -Y http.request -T fields -e http.user_agent | sort | uniq -c | sort -rn | awk '{c=$1;$1="";print c","substr($0,2)}'
} > "$OUT/05_user_agent_counts.csv"

# 4. Outbound SMTP connection attempts
# One row per connection attempt = unique (server, source port); 475 SYN packets collapse to 239 attempts.
# (tcp.stream gives 290 because tshark splits some delayed SYN retries into new streams.)
{ echo "first_syn_time_utc,dst_ip,src_port,syn_packets,answered"
  tshark -r "$PCAP" -Y 'tcp.srcport==25 && tcp.flags.syn==1 && tcp.flags.ack==1' -T fields -e ip.src -e tcp.dstport | sort -u > "$OUT/.synack"
  tshark -r "$PCAP" -Y 'tcp.flags.syn==1 && tcp.flags.ack==0 && tcp.dstport==25' -T fields -e frame.time_epoch -e ip.dst -e tcp.srcport \
  | awk -F'\t' -v ack="$OUT/.synack" 'BEGIN{while((getline l<ack)>0){split(l,a,"\t");A[a[1]","a[2]]=1}}
      {k=$2","$3; if(!(k in T)){T[k]=$1;o[++n]=k} c[k]++}
      END{for(i=1;i<=n;i++){k=o[i]; print strftime("%Y-%m-%d %H:%M:%S",T[k])","k","c[k]","((k in A)?"yes":"no")}}'
  rm -f "$OUT/.synack"
} > "$OUT/06_smtp_connections.csv"

# 5. Carve executables and hash (files themselves are NOT kept in the repo)
TMP=$(mktemp -d); tshark -r "$PCAP" -q --export-objects "http,$TMP" >/dev/null
# gerv.gun is not exported by tshark (stream 0); reassemble it from the raw TCP stream
tshark -r "$PCAP" -q -z follow,tcp,raw,0 | python3 -I -c '
import sys,re
srv=b"".join(bytes.fromhex(l.strip()) for l in sys.stdin if re.fullmatch(r"\t[0-9a-f]+\n?",l))
open(sys.argv[1],"wb").write(srv[srv.find(b"\r\n\r\n")+4:])' "$TMP/gerv.gun"
{ echo "file,bytes,sha256,first_two_bytes_hex (4d5a = MZ executable)"
  for f in gerv.gun trow.exe wp.exe t64.bin; do
    echo "$f,$(stat -c%s "$TMP/$f"),$(sha256sum "$TMP/$f" | cut -c1-64),$(head -c2 "$TMP/$f" | od -An -tx1 | tr -d ' ')"
  done
} > "$OUT/07_payload_hashes.csv"
# t64.bin: entropy and header check (backs the "most likely encrypted" claim)
python3 -I -c '
import sys,math,collections
d=open(sys.argv[1],"rb").read(); c=collections.Counter(d); n=len(d)
e=-sum(v/n*math.log2(v/n) for v in c.values())
sigs={b"PK\x03\x04":"zip",b"\x1f\x8b":"gzip",b"7z\xbc\xaf":"7z",b"Rar!":"rar",b"BZh":"bzip2",b"\xfd7zXZ":"xz",b"MZ":"PE",b"MSCF":"cab"}
m=[v for k,v in sigs.items() if d.startswith(k)]; h=m[0] if m else "none"
print(f"file: t64.bin\nbytes: {n}\nshannon_entropy_bits_per_byte: {e:.5f} (max 8.0)\nfirst_8_bytes_hex: {d[:8].hex()}\nknown_file_or_compression_header: {h}")' "$TMP/t64.bin" > "$OUT/10_t64_entropy.txt"
rm -rf "$TMP"

# 6. Evidence file integrity
sha256sum "$PCAP" "$SNORT" "$SURI" > "$OUT/00_evidence_sha256.txt"
echo "Done: $OUT"
